const lines = [
  '#!/usr/bin/env bash',
  '# Auto-generated by services/tools/clip-plan.mjs',
  '# Chalao repo root se:  bash services/clips/cut-clips.sh',
  '# Zaroorat: ffmpeg (libx264)',
  '',
  'set -euo pipefail',
  'OUT="services/clips/out"',
  'mkdir -p "$OUT"',
  '',
];

const plan = [];

for (const c of clips) {
  const name = `post-${String(c.n).padStart(2, '0')}-${c.type}`;
  const file = `${name}.mp4`;
  // Re-encode (not copy) so the clip starts exactly on the requested frame
  lines.push(
    `echo "→ ${file}"`,
    `ffmpeg -hide_banner -loglevel error -y -ss ${c.from} -to ${c.to} \\`,
    `  -i "${DEMOS}/${c.src}" \\`,
    `  -vf "scale=1080:1920:force_original_aspect_ratio=decrease,pad=1080:1920:(ow-iw)/2:(oh-ih)/2" \\`,
    `  -c:v libx264 -profile:v high -crf 20 -preset medium -pix_fmt yuv420p \\`,
    `  -c:a aac -b:a 128k -movflags +faststart "$OUT/${file}"`,
    ''
  );
  plan.push({ ...c, file, hook: c.hook });
}

writeFileSync(resolve(outDir, 'cut-clips.sh'), lines.join('\n'), { mode: 0o755 });

